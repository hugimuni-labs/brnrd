"""INDEX.md and CLAUDE.md: derived by the self's recipe, folded in by send-self, judged by 30-index."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

from brr.loom.runtime.merge import install_pre_receive, send_to_self
from brr.loom.runtime.selfrepo import init_self, seed_root

from test_merge import commit, copy_seed, git, published, room, show, write

INDEX = seed_root() / "core" / "loom" / "index"


def run_index(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    return subprocess.run([os.fspath(INDEX), *args], cwd=repo, env=env, capture_output=True, text=True)


def fold(repo: Path) -> None:
    """What send-self does at a landing: regenerate at HEAD and amend."""
    assert run_index(repo, "--write").returncode == 0
    git(repo, "add", "-A")
    git(repo, "commit", "--amend", "--no-edit")


def test_the_index_derives_rows_from_the_tree(tmp_path: Path) -> None:
    bare = published(tmp_path)
    work = room(bare, tmp_path / "w", "strand/w")
    write(work, "threads/old/README.md",
          "---\nid: old\nstatus: settled\ntense: plan\n---\n# Old work, done\n")
    write(work, "threads/old/report.md", "# What shipped\n\nbody\n")
    commit(work, "old thread")
    write(work, "threads/fresh/README.md",
          "---\nid: fresh\nstatus: open\ntense: plan\nopened-by: thread:inbox\n"
          "opened-for: [w-abc]\nwish-w-abc: \"Split it out, cleanly\"\n---\n# Fresh work\n")
    write(work, "threads/fresh/research/notes.md", "---\nkind: notes\n---\n# Sources\n\n" + "x" * 3000 + "\n")
    write(work, "memory/scars/git/rebase-dirty.md", "---\ntrigger: rebase\n---\n# Rebase on a dirty tree\n")
    write(work, "memory/scars/git/index.md", "# git scars\n")
    write(work, "people/ada/agreement.md", "# Agreement with ada\n")
    commit(work, "fresh thread")
    text = run_index(work).stdout
    assert text.startswith("# Index\n")
    assert text.index("### open") < text.index("- **[fresh](threads/fresh/README.md)** · open · w-abc Split it out, cleanly · Fresh work")
    assert "  - [research/notes.md](threads/fresh/research/notes.md) · Sources · 2 KB" in text
    assert text.index("### settled (") < text.index("- **[old](threads/old/README.md)** · settled · Old work, done")
    assert "  - [report.md](threads/old/report.md) · What shipped · <1 KB" in text
    assert text.index("[fresh]") < text.index("[inbox]") < text.index("### settled")
    assert "- [scars/git/](memory/scars/git/index.md) · 1 scars" in text
    assert "- [scars/x.md](memory/scars/x.md) · base · <1 KB" in text
    assert "- [stance.md](memory/stance.md)" in text
    assert text.rstrip().endswith("## people\n\n- ada")
    assert "Agreement with ada" not in text
    assert run_index(work).stdout == text
    assert run_index(work, "--rev", "HEAD").stdout == text


def test_the_scar_folder_index_derives_from_its_scars(tmp_path: Path) -> None:
    bare = published(tmp_path)
    work = room(bare, tmp_path / "w", "strand/w")
    write(work, "memory/scars/git/rebase-dirty.md",
          "# Rebase on a dirty tree\ntrigger: rebase,  dirty tree, stash\n\n2026-10-02, mine. body\n")
    write(work, "memory/scars/git/force-push.md",
          "---\ntrigger: force push\n---\n# A force push after a failed rebase closes the PR\n\nSeen 2026-10-19.\n")
    write(work, "memory/scars/git/undated.md", "# No date yet\n\nTrigger: anything\n")
    write(work, "memory/scars/shell/blank.md", "# The blank variable\ntrigger: ${VAR}\n2025-01-01\n")
    write(work, "memory/scars/shell/index.md", "# a stale hand-written index\n")
    commit(work, "scars")
    assert run_index(work, "--write").returncode == 0
    text = (work / "memory/scars/git/index.md").read_text()
    assert text.startswith("# Scars: git (3)\n\nGenerated by `core/loom/index` at every landing: do not edit. ")
    assert "[AGENTS.md](../../../AGENTS.md)" in text
    rows = [line for line in text.splitlines() if line.startswith("- ")]
    assert rows == [
        "- [force-push.md](force-push.md) · A force push after a failed rebase closes the PR · force push · 2026-10-19",
        "- [rebase-dirty.md](rebase-dirty.md) · Rebase on a dirty tree · rebase, dirty tree, stash · 2026-10-02",
        "- [undated.md](undated.md) · No date yet · anything",
    ]
    assert (work / "memory/scars/shell/index.md").read_text().endswith(
        "- [blank.md](blank.md) · The blank variable · ${VAR} · 2025-01-01\n")
    root = (work / "INDEX.md").read_text()
    assert "- [scars/git/](memory/scars/git/index.md) · 3 scars" in root
    assert "- [scars/shell/](memory/scars/shell/index.md) · 1 scars" in root
    commit(work, "indexes")
    assert run_index(work, "--check").returncode == 0
    # The root row linked the folder index before it was in the tree, so the landing does not flip it.
    assert (work / "INDEX.md").read_text() == root
    write(work, "memory/scars/git/index.md", text + "- hand-added row\n")
    write(work, "memory/scars/git/undated.md", "# No date yet, now dated\n\nTrigger: anything\n2026-10-21\n")  # 45-scars would refuse it
    commit(work, "hand edit")
    checked = run_index(work, "--check")
    assert checked.returncode == 1
    assert "memory/scars/git/index.md: differs from core/loom/index at HEAD" in checked.stderr
    pushed = git(work, "push", "origin", "HEAD:main", check=False)
    assert pushed.returncode != 0
    assert "30-index: memory/scars/git/index.md: differs from core/loom/index" in pushed.stderr
    git(work, "rm", "-q", "memory/scars/git/index.md", "memory/scars/shell/blank.md")
    git(work, "commit", "-qm", "index gone, last shell scar gone")
    checked = run_index(work, "--check")
    assert checked.returncode == 1
    assert "memory/scars/git/index.md: missing; run core/loom/index --write and commit" in checked.stderr
    assert "memory/scars/shell/index.md: no scars beside it; run core/loom/index --write and commit" in checked.stderr
    assert run_index(work, "--write").returncode == 0
    assert not (work / "memory/scars/shell/index.md").exists()
    assert (work / "memory/scars/git/index.md").exists()
    commit(work, "regenerated")
    assert run_index(work, "--check").returncode == 0
    pushed = git(work, "push", "origin", "HEAD:main", check=False)
    assert pushed.returncode == 0, pushed.stderr


def test_a_scar_folder_from_before_the_index_lands_without_one(tmp_path: Path) -> None:
    """The old loom's send-self stages only INDEX.md and CLAUDE.md: a folder that had no index keeps passing until one lands."""
    bare = tmp_path / "self.git"
    seed = tmp_path / "seed"
    git(None, "init", "--bare", "-b", "main", os.fspath(bare))
    git(None, "init", "-b", "main", os.fspath(seed))
    copy_seed(seed)
    (seed / "core" / "loom" / "index").unlink()
    write(seed, "threads/inbox/README.md", "---\nid: inbox\nstatus: open\ntense: plan\n---\n# Inbox\n")
    write(seed, "memory/scars/git/old.md", "# Old\ntrigger: old\n2026-10-01\n")
    commit(seed, "a self from before the recipe")
    git(seed, "remote", "add", "origin", os.fspath(bare))
    install_pre_receive(bare)
    assert git(seed, "push", "origin", "HEAD:main", check=False).returncode == 0
    work = room(bare, tmp_path / "w", "strand/w")
    (work / "core" / "loom" / "index").write_bytes(INDEX.read_bytes())
    (work / "core" / "loom" / "index").chmod(0o755)
    commit(work, "the recipe arrives")
    assert run_index(work, "--write").returncode == 0
    (work / "memory/scars/git/index.md").unlink()  # the old fold did not stage it
    git(work, "add", "INDEX.md", "CLAUDE.md")
    git(work, "commit", "-q", "--amend", "--no-edit")
    pushed = git(work, "push", "origin", "HEAD:main", check=False)
    assert pushed.returncode == 0, pushed.stderr
    # A brand-new folder gets no such tolerance.
    write(work, "memory/scars/shell/new.md", "# New\ntrigger: new\n2026-10-21\n")
    commit(work, "a new folder, no index")
    pushed = git(work, "push", "origin", "HEAD:main", check=False)
    assert pushed.returncode != 0
    assert "30-index: memory/scars/shell/index.md: missing" in pushed.stderr
    assert "memory/scars/git/index.md" not in pushed.stderr
    # Once the index lands, the tolerance is over.
    fold(work)
    assert git(work, "push", "origin", "HEAD:main", check=False).returncode == 0
    git(work, "rm", "-q", "memory/scars/git/index.md")
    git(work, "commit", "-qm", "drop it again")
    pushed = git(work, "push", "origin", "HEAD:main", check=False)
    assert pushed.returncode != 0
    assert "30-index: memory/scars/git/index.md: missing" in pushed.stderr


def test_send_self_folds_the_scar_folder_index(tmp_path: Path) -> None:
    bare = published(tmp_path)
    work = room(bare, tmp_path / "w", "strand/w")
    write(work, "memory/scars/git/one.md", "# One\ntrigger: one\n2026-10-20\n")
    commit(work, "one scar")
    landed = send_to_self(work)
    assert landed.status == "merged", landed.stderr
    assert "- [one.md](one.md) · One · one · 2026-10-20" in show(bare, "memory/scars/git/index.md")
    assert git(bare, "log", "-1", "--format=%s", "main").stdout.strip() == "one scar"
    other = room(bare, tmp_path / "o", "strand/o")
